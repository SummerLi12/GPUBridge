/*
 * One op's complete pipeline state (section 9's "Pipeline construction"
 * list, generalized beyond vector_add_f32 to every op this backend
 * implements — see the top-of-file comment's "beyond spec4.5.md's own
 * scope" note). Each op gets its own descriptor set layout/pipeline
 * layout/shader module/pipeline/descriptor pool+set, built once in
 * vulkan_init() via build_op_pipeline() and reused across every launch of
 * that op — same reuse-is-safe-because-every-call-fence-waits reasoning
 * section 9 item 5 already established for vector_add_f32, unchanged by
 * having five of these instead of one. Declared before `g` below since `g`
 * embeds five of these directly (not pointers), so the full type must
 * already be known.
 */
typedef struct {
    VkDescriptorSetLayout descriptor_set_layout;
    VkPipelineLayout pipeline_layout;
    VkShaderModule shader_module;
    VkPipeline pipeline;
    VkDescriptorPool descriptor_pool;
    VkDescriptorSet descriptor_set;
} GpuBridgeVulkanOpPipeline;

